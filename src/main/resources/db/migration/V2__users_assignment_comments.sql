CREATE TABLE app_users (
                           id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           name       VARCHAR(100) NOT NULL,
                           email      VARCHAR(255) NOT NULL,
                           created_at TIMESTAMPTZ  NOT NULL,
                           CONSTRAINT uk_app_users_email UNIQUE (email)
);

ALTER TABLE cases
    ADD COLUMN assignee_id BIGINT REFERENCES app_users (id),
    ADD COLUMN version     BIGINT NOT NULL DEFAULT 0;

CREATE INDEX idx_cases_assignee_id ON cases (assignee_id);
CREATE INDEX idx_cases_status      ON cases (status);

CREATE TABLE case_comments (
                               id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               case_id    BIGINT      NOT NULL REFERENCES cases (id) ON DELETE CASCADE,
                               author_id  BIGINT      NOT NULL REFERENCES app_users (id),
                               body       TEXT        NOT NULL,
                               created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_case_comments_case_id ON case_comments (case_id);